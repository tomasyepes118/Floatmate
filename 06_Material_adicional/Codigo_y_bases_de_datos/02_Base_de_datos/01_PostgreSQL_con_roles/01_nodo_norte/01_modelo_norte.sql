/*
  FLOATMATE - NODO TERMINAL NORTE
  Ejecutar conectado a la base de datos: floatmate_norte
  Este nodo almacena exclusivamente el fragmento horizontal NOR.
*/

BEGIN;

CREATE SCHEMA IF NOT EXISTS floatmate;
COMMENT ON SCHEMA floatmate IS
  'Esquema relacional de FloatMate. Fragmento horizontal de la Terminal Norte.';

SET search_path TO floatmate, pg_catalog;

CREATE TABLE usuarios (
    usuario_id       bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    terminal_codigo  varchar(3)  NOT NULL DEFAULT 'NOR' CHECK (terminal_codigo = 'NOR'),
    documento        varchar(20) NOT NULL UNIQUE,
    nombres          varchar(60) NOT NULL,
    apellidos        varchar(60) NOT NULL,
    correo           varchar(120) NOT NULL UNIQUE CHECK (position('@' IN correo) > 1),
    rol              varchar(20) NOT NULL CHECK (rol IN ('ADMINISTRADOR', 'OPERADOR', 'CONSULTA')),
    activo           boolean NOT NULL DEFAULT true,
    creado_en        timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE conductores (
    conductor_id       bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    terminal_codigo    varchar(3)  NOT NULL DEFAULT 'NOR' CHECK (terminal_codigo = 'NOR'),
    documento          varchar(20) NOT NULL UNIQUE,
    nombres            varchar(60) NOT NULL,
    apellidos          varchar(60) NOT NULL,
    numero_licencia    varchar(30) NOT NULL UNIQUE,
    categoria_licencia varchar(4)  NOT NULL CHECK (categoria_licencia IN ('C1', 'C2', 'C3')),
    licencia_vence     date NOT NULL,
    telefono           varchar(20) NOT NULL,
    estado             varchar(15) NOT NULL CHECK (estado IN ('DISPONIBLE', 'EN_VIAJE', 'INACTIVO'))
);

CREATE TABLE vehiculos (
    vehiculo_id              bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    terminal_codigo          varchar(3)  NOT NULL DEFAULT 'NOR' CHECK (terminal_codigo = 'NOR'),
    placa                    varchar(6)  NOT NULL UNIQUE CHECK (placa ~ '^[A-Z]{3}[0-9]{3}$'),
    codigo_interno           varchar(15) NOT NULL UNIQUE,
    tipo                     varchar(25) NOT NULL CHECK (tipo IN ('BUS_URBANO', 'BUS_INTERMUNICIPAL', 'MICROBUS')),
    marca                    varchar(40) NOT NULL,
    modelo                   smallint NOT NULL CHECK (modelo BETWEEN 2000 AND 2035),
    capacidad_pasajeros      smallint NOT NULL CHECK (capacidad_pasajeros BETWEEN 10 AND 80),
    kilometraje              numeric(12,2) NOT NULL CHECK (kilometraje >= 0),
    proximo_mantenimiento_km numeric(12,2) NOT NULL CHECK (proximo_mantenimiento_km >= 0),
    estado                   varchar(20) NOT NULL CHECK (estado IN ('DISPONIBLE', 'EN_RUTA', 'MANTENIMIENTO', 'FUERA_SERVICIO'))
);

CREATE TABLE rutas (
    ruta_id          bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    terminal_codigo  varchar(3)  NOT NULL DEFAULT 'NOR' CHECK (terminal_codigo = 'NOR'),
    codigo           varchar(15) NOT NULL UNIQUE,
    nombre           varchar(100) NOT NULL,
    origen           varchar(100) NOT NULL,
    destino          varchar(100) NOT NULL CHECK (destino <> origen),
    tipo             varchar(20) NOT NULL CHECK (tipo IN ('URBANA', 'INTERMUNICIPAL')),
    distancia_km     numeric(8,2) NOT NULL CHECK (distancia_km > 0),
    duracion_minutos smallint NOT NULL CHECK (duracion_minutos > 0),
    activa           boolean NOT NULL DEFAULT true
);

CREATE TABLE viajes (
    viaje_id               bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    terminal_codigo        varchar(3) NOT NULL DEFAULT 'NOR' CHECK (terminal_codigo = 'NOR'),
    vehiculo_id            bigint NOT NULL REFERENCES vehiculos(vehiculo_id) ON DELETE RESTRICT,
    conductor_id           bigint NOT NULL REFERENCES conductores(conductor_id) ON DELETE RESTRICT,
    ruta_id                bigint NOT NULL REFERENCES rutas(ruta_id) ON DELETE RESTRICT,
    fecha_hora_programada  timestamptz NOT NULL,
    fecha_hora_salida      timestamptz,
    fecha_hora_llegada     timestamptz,
    pasajeros              smallint NOT NULL CHECK (pasajeros >= 0),
    estado                 varchar(15) NOT NULL CHECK (estado IN ('PROGRAMADO', 'EN_CURSO', 'FINALIZADO', 'CANCELADO')),
    observaciones          varchar(250),
    CONSTRAINT ck_viaje_fechas CHECK (
        fecha_hora_llegada IS NULL OR
        (fecha_hora_salida IS NOT NULL AND fecha_hora_llegada >= fecha_hora_salida)
    ),
    CONSTRAINT uq_viaje_vehiculo_hora UNIQUE (vehiculo_id, fecha_hora_programada),
    CONSTRAINT uq_viaje_conductor_hora UNIQUE (conductor_id, fecha_hora_programada)
);

CREATE TABLE controles_salida (
    control_id          bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    terminal_codigo     varchar(3) NOT NULL DEFAULT 'NOR' CHECK (terminal_codigo = 'NOR'),
    viaje_id            bigint NOT NULL UNIQUE REFERENCES viajes(viaje_id) ON DELETE CASCADE,
    usuario_id          bigint NOT NULL REFERENCES usuarios(usuario_id) ON DELETE RESTRICT,
    fecha_hora_control  timestamptz NOT NULL,
    alcoholemia_mg_l    numeric(5,3) NOT NULL CHECK (alcoholemia_mg_l >= 0),
    resultado           varchar(12) NOT NULL CHECK (resultado IN ('APROBADO', 'RECHAZADO')),
    numero_ticket       varchar(40) NOT NULL UNIQUE,
    observaciones       varchar(250),
    CONSTRAINT ck_control_resultado CHECK (
        (resultado = 'APROBADO' AND alcoholemia_mg_l = 0) OR
        (resultado = 'RECHAZADO' AND alcoholemia_mg_l > 0)
    )
);

CREATE TABLE abastecimientos (
    abastecimiento_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    terminal_codigo   varchar(3) NOT NULL DEFAULT 'NOR' CHECK (terminal_codigo = 'NOR'),
    vehiculo_id       bigint NOT NULL REFERENCES vehiculos(vehiculo_id) ON DELETE RESTRICT,
    viaje_id          bigint REFERENCES viajes(viaje_id) ON DELETE SET NULL,
    usuario_id        bigint NOT NULL REFERENCES usuarios(usuario_id) ON DELETE RESTRICT,
    fecha_hora        timestamptz NOT NULL,
    litros            numeric(8,2) NOT NULL CHECK (litros > 0),
    valor_litro       numeric(10,2) NOT NULL CHECK (valor_litro > 0),
    valor_total       numeric(12,2) NOT NULL CHECK (valor_total > 0),
    kilometraje       numeric(12,2) NOT NULL CHECK (kilometraje >= 0),
    estacion_servicio varchar(100) NOT NULL,
    numero_factura    varchar(40) NOT NULL UNIQUE,
    CONSTRAINT ck_abastecimiento_total CHECK (valor_total = round(litros * valor_litro, 2))
);

CREATE TABLE mantenimientos (
    mantenimiento_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    terminal_codigo  varchar(3) NOT NULL DEFAULT 'NOR' CHECK (terminal_codigo = 'NOR'),
    vehiculo_id      bigint NOT NULL REFERENCES vehiculos(vehiculo_id) ON DELETE RESTRICT,
    usuario_id       bigint NOT NULL REFERENCES usuarios(usuario_id) ON DELETE RESTRICT,
    tipo             varchar(15) NOT NULL CHECK (tipo IN ('PREVENTIVO', 'CORRECTIVO')),
    fecha_ingreso    date NOT NULL,
    fecha_salida     date,
    kilometraje      numeric(12,2) NOT NULL CHECK (kilometraje >= 0),
    costo            numeric(12,2) NOT NULL CHECK (costo >= 0),
    proveedor        varchar(100) NOT NULL,
    descripcion      varchar(300) NOT NULL,
    estado           varchar(15) NOT NULL CHECK (estado IN ('PROGRAMADO', 'EN_PROCESO', 'FINALIZADO')),
    CONSTRAINT ck_mantenimiento_fechas CHECK (fecha_salida IS NULL OR fecha_salida >= fecha_ingreso)
);

CREATE TABLE incidentes (
    incidente_id   bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    terminal_codigo varchar(3) NOT NULL DEFAULT 'NOR' CHECK (terminal_codigo = 'NOR'),
    viaje_id       bigint NOT NULL REFERENCES viajes(viaje_id) ON DELETE RESTRICT,
    usuario_id     bigint NOT NULL REFERENCES usuarios(usuario_id) ON DELETE RESTRICT,
    fecha_hora     timestamptz NOT NULL,
    tipo           varchar(25) NOT NULL CHECK (tipo IN ('MECANICO', 'TRANSITO', 'SEGURIDAD', 'OPERATIVO')),
    severidad      varchar(10) NOT NULL CHECK (severidad IN ('BAJA', 'MEDIA', 'ALTA')),
    descripcion    varchar(300) NOT NULL,
    ubicacion      varchar(150) NOT NULL,
    tiene_evidencia boolean NOT NULL DEFAULT false,
    estado         varchar(15) NOT NULL CHECK (estado IN ('ABIERTO', 'EN_REVISION', 'CERRADO'))
);

CREATE INDEX ix_viajes_fecha ON viajes(fecha_hora_programada);
CREATE INDEX ix_viajes_ruta ON viajes(ruta_id);
CREATE INDEX ix_abastecimientos_fecha ON abastecimientos(fecha_hora);
CREATE INDEX ix_mantenimientos_vehiculo ON mantenimientos(vehiculo_id, fecha_ingreso);
CREATE INDEX ix_incidentes_viaje ON incidentes(viaje_id);

COMMENT ON COLUMN viajes.terminal_codigo IS
  'Clave de fragmentacion horizontal. En este nodo solo se admite NOR.';

COMMIT;
